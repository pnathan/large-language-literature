#   lines       the English, one entry per printed line
#   commentary  root notes, witness readings, and the register choices made
#
# Register: strange, messy, bodily, and at times gasping. Fragments, doubled nouns,
# verbs that land too hard, sentences that do not close. The reader has met this
# text in English many times; the aim is a text they do not recognise. No frame is
# added: the speaker is the narrator of the Hebrew, nothing more. Every place the
# register bends the Hebrew is named in the commentary.
#
# Translated from the Hebrew witness, with the LXX (witness-lxx.json) as a second
# witness. No English rendering was consulted.

